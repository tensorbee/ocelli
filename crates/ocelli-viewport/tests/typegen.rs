//! F-104. The generated TypeScript boundary declarations, emitted from Rust.
//!
//! `UPDATE_TYPES=1` rewrites `packages/core/src/generated.ts`. Without it, the
//! test compares the committed file byte for byte and fails on the first
//! differing line. The file is committed, so a clean clone needs no codegen
//! step to type-check.
//!
//! The numbers come from `crates/ocelli-viewport/src/boundary.rs` and from the
//! real `#[repr(C)]` layouts, not from literals in this file. A change to a
//! Rust payload length or a struct field moves this test and the TypeScript
//! reader together, which is the point of F-104.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use bytemuck::Zeroable;
use ocelli_viewport::boundary::{
    COLORMAP_BYTES, COMMAND_TABLE, EVENT_HEADER_BYTES, EVENT_KIND_OFFSET, EVENT_PAYLOAD_BYTES,
    EVENT_PAYLOAD_OFFSET, EVENT_RING_CAPACITY_OFFSET, EVENT_RING_DROPPED_OFFSET,
    EVENT_RING_PENDING_OFFSET, EVENT_RING_TAIL_OFFSET, EVENT_SEQ_OFFSET, EVENT_STRIDE,
    EVENT_VIEWPORT_OFFSET, FLAG_ERROR, FLAG_INVERT, FLAG_LOADING, FLAG_REFINING, INVERT_BYTES,
    PRESET_BYTES, RING_EVENT_KINDS, VOI_FUNCTION_BYTES, ViewportState,
};
use ocelli_viewport::snapshot::{SNAPSHOT_ERRORS, SNAPSHOT_MAGIC, SNAPSHOT_VERSION};

const HEADER: &str = "\
// Generated by crates/ocelli-viewport/tests/typegen.rs. Do not edit.
// Regenerate with UPDATE_TYPES=1 cargo test -p ocelli-viewport --test typegen.

";

fn generated() -> String {
    let state: ViewportState = Zeroable::zeroed();
    let camera_components = core::mem::size_of_val(&state.camera) / core::mem::size_of::<f32>();
    let mut out = String::from(HEADER);

    let _ = writeln!(
        out,
        "export const VIEWPORT_STATE_BYTES = {};",
        core::mem::size_of::<ViewportState>()
    );
    let _ = writeln!(
        out,
        "export const STATE_CAMERA_OFFSET = {};",
        core::mem::offset_of!(ViewportState, camera)
    );
    let _ = writeln!(
        out,
        "export const STATE_CAMERA_COMPONENTS = {camera_components};"
    );
    let _ = writeln!(
        out,
        "export const STATE_CAMERA_COMPONENT_BYTES = {};",
        core::mem::size_of::<f32>()
    );
    let _ = writeln!(
        out,
        "export const STATE_VOI_CENTER_OFFSET = {};",
        core::mem::offset_of!(ViewportState, voi_center)
    );
    let _ = writeln!(
        out,
        "export const STATE_VOI_WIDTH_OFFSET = {};",
        core::mem::offset_of!(ViewportState, voi_width)
    );
    let _ = writeln!(
        out,
        "export const STATE_SLICE_INDEX_OFFSET = {};",
        core::mem::offset_of!(ViewportState, slice_index)
    );
    let _ = writeln!(
        out,
        "export const STATE_NUM_SLICES_OFFSET = {};",
        core::mem::offset_of!(ViewportState, num_slices)
    );
    let _ = writeln!(
        out,
        "export const STATE_FLAGS_OFFSET = {};",
        core::mem::offset_of!(ViewportState, flags)
    );
    let _ = writeln!(
        out,
        "export const STATE_PADDING_OFFSET = {};",
        core::mem::offset_of!(ViewportState, padding)
    );
    out.push('\n');

    let _ = writeln!(
        out,
        "export const EVENT_HEADER_BYTES = {EVENT_HEADER_BYTES};"
    );
    let _ = writeln!(out, "export const EVENT_STRIDE = {EVENT_STRIDE};");
    let _ = writeln!(
        out,
        "export const EVENT_PAYLOAD_BYTES = {EVENT_PAYLOAD_BYTES};"
    );
    let _ = writeln!(out, "export const EVENT_KIND_OFFSET = {EVENT_KIND_OFFSET};");
    let _ = writeln!(
        out,
        "export const EVENT_VIEWPORT_OFFSET = {EVENT_VIEWPORT_OFFSET};"
    );
    let _ = writeln!(out, "export const EVENT_SEQ_OFFSET = {EVENT_SEQ_OFFSET};");
    let _ = writeln!(
        out,
        "export const EVENT_PAYLOAD_OFFSET = {EVENT_PAYLOAD_OFFSET};"
    );
    let _ = writeln!(
        out,
        "export const EVENT_RING_PENDING_OFFSET = {EVENT_RING_PENDING_OFFSET};"
    );
    let _ = writeln!(
        out,
        "export const EVENT_RING_TAIL_OFFSET = {EVENT_RING_TAIL_OFFSET};"
    );
    let _ = writeln!(
        out,
        "export const EVENT_RING_CAPACITY_OFFSET = {EVENT_RING_CAPACITY_OFFSET};"
    );
    let _ = writeln!(
        out,
        "export const EVENT_RING_DROPPED_OFFSET = {EVENT_RING_DROPPED_OFFSET};"
    );
    out.push('\n');

    out.push_str("export const COMMAND_ID = {\n");
    for spec in &COMMAND_TABLE {
        let _ = writeln!(out, "  {}: {},", spec.name, spec.kind);
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const COMMAND_PAYLOAD_BYTES = {\n");
    for spec in &COMMAND_TABLE {
        let _ = writeln!(out, "  {}: {},", spec.name, spec.payload_bytes);
    }
    out.push_str("} as const;\n\n");

    out.push_str("export const STACK_COMMANDS = [\n");
    for spec in &COMMAND_TABLE {
        let _ = writeln!(out, "  \"{}\",", spec.name);
    }
    out.push_str("] as const;\n\n");
    out.push_str("export type StackCommand = (typeof STACK_COMMANDS)[number];\n\n");

    push_u8_table(&mut out, "VOI_FUNCTION_BYTE", &VOI_FUNCTION_BYTES);
    push_u8_table(&mut out, "PRESET_BYTE", &PRESET_BYTES);
    push_u8_table(&mut out, "COLORMAP_BYTE", &COLORMAP_BYTES);
    push_u8_table(&mut out, "INVERT_BYTE", &INVERT_BYTES);

    out.push_str("export const RING_EVENT_KIND = {\n");
    for (name, kind) in RING_EVENT_KINDS {
        let _ = writeln!(out, "  {name}: {kind},");
    }
    out.push_str("} as const;\n\n");

    let _ = writeln!(out, "export const FLAG_INVERT = {FLAG_INVERT};");
    let _ = writeln!(out, "export const FLAG_LOADING = {FLAG_LOADING};");
    let _ = writeln!(out, "export const FLAG_ERROR = {FLAG_ERROR};");
    let _ = writeln!(out, "export const FLAG_REFINING = {FLAG_REFINING};");
    out.push('\n');

    let _ = writeln!(out, "export const SNAPSHOT_MAGIC = \"{SNAPSHOT_MAGIC}\";");
    let _ = writeln!(out, "export const SNAPSHOT_VERSION = {SNAPSHOT_VERSION};");
    out.push_str("export const SNAPSHOT_ERROR = {\n");
    for (name, code) in SNAPSHOT_ERRORS {
        let _ = writeln!(out, "  {name}: {code},");
    }
    out.push_str("} as const;\n");

    out
}

fn push_u8_table(out: &mut String, name: &str, rows: &[(&str, u8)]) {
    let _ = writeln!(out, "export const {name} = {{");
    for (key, byte) in rows {
        let _ = writeln!(out, "  {key}: {byte},");
    }
    out.push_str("} as const;\n\n");
}

fn generated_path() -> PathBuf {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let found = manifest.parent().and_then(Path::parent);
    assert!(
        found.is_some(),
        "the workspace root cannot be found from {}",
        manifest.display()
    );
    let root = found.unwrap_or(Path::new(""));
    let source = root.join("packages").join("core").join("src");
    assert!(
        source.is_dir(),
        "ocelli-viewport must sit inside the workspace, and {} is not a directory",
        source.display()
    );
    source.join("generated.ts")
}

fn write_atomic(path: &Path, bytes: &[u8]) {
    let temporary = path.with_file_name("generated.ts.tmp");
    let written = std::fs::write(&temporary, bytes);
    assert!(
        written.is_ok(),
        "cannot write {}: {written:?}",
        temporary.display()
    );
    let renamed = std::fs::rename(&temporary, path);
    assert!(
        renamed.is_ok(),
        "cannot rename {} to {}: {renamed:?}",
        temporary.display(),
        path.display()
    );
}

fn first_difference(actual: &[u8], expected: &[u8]) -> String {
    let actual_text = String::from_utf8_lossy(actual);
    let expected_text = String::from_utf8_lossy(expected);
    let mut line = 1;
    for (left, right) in actual_text.lines().zip(expected_text.lines()) {
        if left != right {
            return format!("line {line}: committed {left:?}, generated {right:?}");
        }
        line += 1;
    }
    format!(
        "line {line}: committed has {} lines and generated has {}",
        actual_text.lines().count(),
        expected_text.lines().count()
    )
}

#[test]
fn generated_types_match_the_committed_file() {
    let path = generated_path();
    let expected = generated();
    if std::env::var_os("UPDATE_TYPES").is_some() {
        write_atomic(&path, expected.as_bytes());
        return;
    }
    let read = std::fs::read(&path);
    assert!(read.is_ok(), "cannot read {}: {read:?}", path.display());
    let actual = read.unwrap_or_default();
    assert_eq!(
        actual,
        expected.as_bytes(),
        "packages/core/src/generated.ts is stale: {}. Regenerate with UPDATE_TYPES=1 cargo test -p ocelli-viewport --test typegen.",
        first_difference(&actual, expected.as_bytes())
    );
}

#[test]
fn the_generated_file_names_the_ring_event_the_producer_emits() {
    let text = generated();
    assert!(text.contains("export const RING_EVENT_KIND = {"));
    assert!(text.contains("presented: 6,"));
    assert!(text.contains("export const EVENT_STRIDE = 48;"));
}
