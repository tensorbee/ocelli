//! F-225. The generated conformance catalogue, emitted from Rust.
//!
//! `UPDATE_TYPES=1` rewrites `packages/core/src/conformance.generated.ts`.
//! Without it, the test compares the committed file byte for byte and fails
//! on the first differing line. The file is committed, so a clean clone needs
//! no codegen step to type-check.
//!
//! The identifiers and sections come from `ConformanceRule`. A new variant
//! that is not regenerated fails this test.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use ocelli_dicom::{CONFORMANCE_SCOPE, ConformanceRule, SOP_CLASS_NOTES};

const HEADER: &str = "\
// Generated by crates/ocelli-dicom/tests/conformance_typegen.rs. Do not edit.
// Regenerate with UPDATE_TYPES=1 cargo test -p ocelli-dicom --test conformance_typegen.

";

fn generated() -> String {
    let mut out = String::from(HEADER);
    let _ = writeln!(
        out,
        "export const CONFORMANCE_SCOPE = \"{CONFORMANCE_SCOPE}\";"
    );
    out.push('\n');
    out.push_str("export const CONFORMANCE_RULES = [\n");
    for rule in ConformanceRule::ALL {
        let _ = writeln!(
            out,
            "  {{ id: \"{}\", section: \"{}\" }},",
            rule.id(),
            rule.section()
        );
    }
    out.push_str("] as const;\n");
    out.push('\n');
    out.push_str("export const SOP_CLASS_NOTES = [\n");
    for note in SOP_CLASS_NOTES {
        let _ = writeln!(out, "  \"{note}\",");
    }
    out.push_str("] as const;\n");
    out
}

fn generated_path() -> PathBuf {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
    let found = manifest.parent().and_then(Path::parent);
    assert!(
        found.is_some(),
        "the workspace root cannot be found from {}",
        manifest.display()
    );
    let root = found.unwrap_or(Path::new(""));
    let source = root.join("packages").join("core").join("src");
    assert!(
        source.is_dir(),
        "ocelli-dicom must sit inside the workspace, and {} is not a directory",
        source.display()
    );
    source.join("conformance.generated.ts")
}

fn write_atomic(path: &Path, bytes: &[u8]) {
    let temporary = path.with_file_name("conformance.generated.ts.tmp");
    let written = std::fs::write(&temporary, bytes);
    assert!(
        written.is_ok(),
        "cannot write {}: {written:?}",
        temporary.display()
    );
    let renamed = std::fs::rename(&temporary, path);
    assert!(
        renamed.is_ok(),
        "cannot rename {} to {}: {renamed:?}",
        temporary.display(),
        path.display()
    );
}

fn first_difference(actual: &[u8], expected: &[u8]) -> String {
    let actual_text = String::from_utf8_lossy(actual);
    let expected_text = String::from_utf8_lossy(expected);
    let mut line = 1;
    for (left, right) in actual_text.lines().zip(expected_text.lines()) {
        if left != right {
            return format!("line {line}: committed {left:?}, generated {right:?}");
        }
        line += 1;
    }
    format!(
        "line {line}: committed has {} lines and generated has {}",
        actual_text.lines().count(),
        expected_text.lines().count()
    )
}

#[test]
fn generated_rules_match_the_committed_file() {
    let path = generated_path();
    let expected = generated();
    if std::env::var_os("UPDATE_TYPES").is_some() {
        write_atomic(&path, expected.as_bytes());
        return;
    }
    let read = std::fs::read(&path);
    assert!(read.is_ok(), "cannot read {}: {read:?}", path.display());
    let actual = read.unwrap_or_default();
    assert_eq!(
        actual,
        expected.as_bytes(),
        "packages/core/src/conformance.generated.ts is stale: {}. Regenerate with UPDATE_TYPES=1 cargo test -p ocelli-dicom --test conformance_typegen.",
        first_difference(&actual, expected.as_bytes())
    );
}
